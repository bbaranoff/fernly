#!/usr/bin/env python3
"""Convert the DOS Super Mario clone assets (PCX sprite sheets, LEVEL001.DAT)
into C arrays, slicing them exactly the way gdcfunc.c does."""
import struct, sys, os

SRC = sys.argv[1] if len(sys.argv) > 1 else "."

def pcx_decode(fn):
    d = open(os.path.join(SRC, fn), "rb").read()
    out = bytearray(); i = 128
    while len(out) < 64000 and i < len(d) - 768:
        c = d[i]; i += 1
        if 192 <= c <= 255:
            n = c - 192; v = d[i]; i += 1; out += bytes([v]) * n
        else:
            out.append(c)
    pal = d[-768:]
    return bytes(out), pal

blocks = [None] * 52
bg, _ = pcx_decode("BGRND001.PCX")
bl, pal = pcx_decode("BLOCK001.PCX")
for n in range(26):
    blocks[n] = bytes(bg[n*17 + (r+1)*320 + c + 1] for r in range(16) for c in range(16))
    blocks[n+26] = bytes(bl[n*17 + (r+1)*320 + c + 1] for r in range(16) for c in range(16))
co, _ = pcx_decode("COIN.PCX")
coins = [bytes(co[n*17 + (r+1)*320 + c] for r in range(16) for c in range(16)) for n in range(3)]
ma, _ = pcx_decode("MARIO.PCX")
mario = [bytes(ma[n*17 + (r+1)*320 + c + 1] for r in range(16) for c in range(16)) for n in range(7)]

# level: 12 rows of 216 chars + line ending; column 216 is the line-end char (-> 0)
raw = open(os.path.join(SRC, "LEVEL001.DAT"), "rb").read().replace(b"\r\n", b"\n")
rows = raw.split(b"\n")
world = []
for r in range(12):
    line = rows[r] if r < len(rows) else b""
    vals = []
    for c in range(217):
        ch = line[c] if c < len(line) else 0
        v = 0
        if ch <= ord('0'): v = 0
        if ord('a') <= ch <= ord('z'): v = ch - 70
        if ord('A') <= ch <= ord('Z'): v = ch - 64
        if r == 0: v = 0
        vals.append(v)
    world.append(vals)

def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

with open("assets.h", "w") as f:
    f.write("/* generated by mkassets.py from the DOS Super Mario clone assets */\n")
    f.write("static const unsigned short palette565[256] = {\n")
    for i in range(256):
        f.write("0x%04x," % rgb565(pal[i*3], pal[i*3+1], pal[i*3+2]) + ("\n" if i % 12 == 11 else " "))
    f.write("};\n")
    def dump(name, arrs):
        f.write("static const unsigned char %s[%d][256] = {\n" % (name, len(arrs)))
        for a in arrs:
            f.write("{" + ",".join(str(b) for b in a) + "},\n")
        f.write("};\n")
    dump("block_px", blocks); dump("coin_px", coins); dump("mario_px", mario)
    f.write("static const signed char world_src[12][217] = {\n")
    for row in world:
        f.write("{" + ",".join(str(v) for v in row) + "},\n")
    f.write("};\n")
print("blocks 52, coins 3, mario 7; palette entries", len(pal)//3)
print("world row 11:", "".join("#" if v > 26 else ("." if v == 0 else "b") for v in world[11][:80]))
print("world row 10:", "".join("#" if v > 26 else ("." if v == 0 else "b") for v in world[10][:80]))
print("codes used:", sorted(set(v for row in world for v in row)))
