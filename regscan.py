#!/usr/bin/env python3
"""Probe the MT6260 address space through the fernly shell and write a map.

Drives "peek" over the fernly serial port (no pyserial needed) and classifies
each probed address as a readable value, a data abort (needs the
data_abort_entry in start.S, which resumes after the fault) or a hang.

Usage:
  regscan.py PORT OUT.md [START-END[:STEP] ...]

With no range, scans the modem region 0x82000000-0x83ffffff in 64 KiB
blocks, then dumps the first 16 words of every block that answered.
"""

import os
import re
import select
import sys
import termios
import time

PROMPT = b"fernly> "
VALUE_RE = re.compile(rb"Value at 0x([0-9a-f]{8}): 0x([0-9a-f]{8})")


class Fernly:
    def __init__(self, port, timeout=1.5):
        self.fd = os.open(port, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
        attrs = termios.tcgetattr(self.fd)
        attrs[0] = 0                       # iflag
        attrs[1] = 0                       # oflag
        attrs[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
        attrs[3] = 0                       # lflag: raw, no echo
        attrs[4] = attrs[5] = termios.B115200
        termios.tcsetattr(self.fd, termios.TCSANOW, attrs)
        termios.tcflush(self.fd, termios.TCIOFLUSH)
        self.timeout = timeout
        self.hung = False

    def _read_until_prompt(self, timeout):
        buf = b""
        deadline = time.monotonic() + timeout
        while not buf.endswith(PROMPT):
            left = deadline - time.monotonic()
            if left <= 0:
                return buf, False
            r, _, _ = select.select([self.fd], [], [], left)
            if r:
                try:
                    chunk = os.read(self.fd, 4096)
                except BlockingIOError:
                    continue
                if not chunk:
                    return buf, False
                buf += chunk
        return buf, True

    def _drain(self):
        """Discard anything still buffered (e.g. a stale prompt)."""
        while True:
            r, _, _ = select.select([self.fd], [], [], 0.05)
            if not r:
                return
            try:
                if not os.read(self.fd, 4096):
                    return
            except BlockingIOError:
                return

    def sync(self):
        for _ in range(3):
            self._drain()
            os.write(self.fd, b"\n")
            _, ok = self._read_until_prompt(1.0)
            if ok:
                self._drain()
                return True
        return False

    def command(self, line):
        # fernly treats "\r" and "\n" as two line ends and prints two prompts,
        # so send a bare "\n" and drain leftovers first.
        self._drain()
        os.write(self.fd, line.encode() + b"\n")
        out, ok = self._read_until_prompt(self.timeout)
        if not ok:
            self.hung = True
        return out, ok

    def peek(self, addr):
        """Return int value, "ABORT" or "HANG" (after one resync + retry)."""
        for attempt in range(2):
            out, ok = self.command("peek 0x%08x" % addr)
            if ok:
                if b"Data abort" in out:
                    return "ABORT"
                m = VALUE_RE.search(out)
                if m and int(m.group(1), 16) == addr:
                    self.hung = False
                    return int(m.group(2), 16)
            if not self.sync():
                break
        self.hung = True
        return "HANG"


def parse_range(spec):
    rng, _, step = spec.partition(":")
    start, _, end = rng.partition("-")
    return int(start, 0), int(end, 0), int(step, 0) if step else 0x10000


def fmt(v):
    if isinstance(v, int):
        return "0x%08x" % v
    return v


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    port, out_path = sys.argv[1], sys.argv[2]
    ranges = [parse_range(s) for s in sys.argv[3:]] or [(0x82000000, 0x83ffffff, 0x10000)]

    f = Fernly(port)
    if not f.sync():
        print("no fernly prompt on", port)
        return 1

    lines = ["# MT6260 (Fernvale) register map probe", "",
             "Generated by regscan.py over the fernly shell. Each 64 KiB block "
             "is probed at its first word; blocks that answered are then dumped "
             "16 words deep, read twice to spot live counters.", ""]
    alive = []
    for start, end, step in ranges:
        lines += ["## Coarse scan 0x%08x-0x%08x step 0x%x" % (start, end, step), "",
                  "Unmapped addresses read as 0 on this bus, so a block counts as "
                  "alive when any of its first four words is non-zero.", "",
                  "| base | +0x0 | +0x4 | +0x8 | +0xc |", "|---|---|---|---|---|"]
        addr = start
        while addr <= end:
            words = [f.peek(addr + off) for off in (0, 4, 8, 12)]
            print("%08x %s" % (addr, " ".join(fmt(v) for v in words)), flush=True)
            if "HANG" in words:
                lines += ["| 0x%08x | HANG | | | |" % addr, "",
                          "**Board stopped answering here; replug and rerun from this address.**"]
                open(out_path, "w").write("\n".join(lines) + "\n")
                return 2
            if any(isinstance(v, int) and v != 0 for v in words) or "ABORT" in words:
                alive.append(addr)
            lines.append("| 0x%08x | %s |" % (addr, " | ".join(fmt(v) for v in words)))
            addr += step
        lines.append("")
        open(out_path, "w").write("\n".join(lines) + "\n")   # checkpoint
        lines.append("")

    for base in alive:
        lines += ["## Block 0x%08x" % base, "", "| offset | read 1 | read 2 | note |", "|---|---|---|---|"]
        for off in range(0, 0x40, 4):
            a = f.peek(base + off)
            b = f.peek(base + off)
            note = ""
            if a == "HANG" or b == "HANG":
                note = "hang"
            elif isinstance(a, int) and isinstance(b, int) and a != b:
                note = "changes between reads (counter/status?)"
            lines.append("| 0x%02x | %s | %s | %s |" % (off, fmt(a), fmt(b), note))
            print("%08x+%02x %s %s %s" % (base, off, fmt(a), fmt(b), note), flush=True)
            if note == "hang":
                open(out_path, "w").write("\n".join(lines) + "\n")
                return 2
        lines.append("")

    open(out_path, "w").write("\n".join(lines) + "\n")
    print("wrote", out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
